-- Función para obtener estadísticas del dashboard
CREATE OR REPLACE FUNCTION public.get_dashboard_stats()
RETURNS JSON AS $$
DECLARE
    result JSON;
BEGIN
    SELECT json_build_object(
        'total_leads', (SELECT COUNT(*) FROM public.contact_messages),
        'new_leads', (SELECT COUNT(*) FROM public.contact_messages WHERE status = 'Nuevo'),
        'in_process', (SELECT COUNT(*) FROM public.contact_messages WHERE status = 'En Proceso'),
        'closed_sales', (SELECT COUNT(*) FROM public.contact_messages WHERE status = 'Cerrado'),
        'total_projects', (SELECT COUNT(*) FROM public.projects),
        'active_projects', (SELECT COUNT(*) FROM public.projects WHERE status IN ('Planificación', 'En Progreso')),
        'pending_appointments', (SELECT COUNT(*) FROM public.appointments WHERE status = 'Programada' AND appointment_date > NOW()),
        'this_month_leads', (SELECT COUNT(*) FROM public.contact_messages WHERE created_at >= date_trunc('month', CURRENT_DATE)),
        'total_kits', (SELECT COUNT(*) FROM public.kits),
        'active_kits', (SELECT COUNT(*) FROM public.kits WHERE is_active = true),
        'total_stock_value', (SELECT COALESCE(SUM(price * stock), 0) FROM public.kits WHERE is_active = true)
    ) INTO result;
    
    RETURN result;
END;
$$ LANGUAGE plpgsql;

