-- 13. VISTAS ÚTILES PARA EL PANEL

-- Vista de clientes con información completa
CREATE OR REPLACE VIEW public.client_dashboard AS
SELECT 
    cm.id,
    cm.nombre,
    cm.empresa,
    cm.email,
    cm.telefono,
    cm.servicio,
    cm.status,
    cm."crmNote",
    cm.created_at,
    COUNT(p.id) as project_count,
    COUNT(a.id) as appointment_count,
    MAX(a.appointment_date) as last_appointment
FROM public.contact_messages cm
LEFT JOIN public.projects p ON cm.id = p.contact_id
LEFT JOIN public.appointments a ON cm.id = a.contact_id
GROUP BY cm.id, cm.nombre, cm.empresa, cm.email, cm.telefono, cm.servicio, cm.status, cm."crmNote", cm.created_at;

-- Vista de proyectos con detalles del cliente
CREATE OR REPLACE VIEW public.project_dashboard AS
SELECT 
    p.id,
    p.project_name,
    p.service_type,
    p.status,
    p.estimated_cost,
    p.actual_cost,
    p.start_date,
    p.completion_date,
    p.city,
    p.state,
    cm.nombre as client_name,
    cm.empresa as client_empresa,
    cm.email as client_email,
    cm.telefono as client_phone
FROM public.projects p
JOIN public.contact_messages cm ON p.contact_id = cm.id;

