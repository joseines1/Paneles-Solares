-- 1. TABLA PRINCIPAL DE MENSAJES/COTIZACIONES (CRM)
CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    empresa TEXT,
    email TEXT NOT NULL,
    telefono TEXT NOT NULL,
    servicio TEXT,
    factura TEXT,
    mensaje TEXT,
    status TEXT DEFAULT 'Nuevo'::text,
    "crmNote" TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. TABLA DE SERVICIOS (CATÁLOGO)
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    base_price DECIMAL(10,2),
    category TEXT DEFAULT 'residencial'::text, -- 'residencial', 'comercial', 'industrial'
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABLA DE PROYECTOS (SEGUIMIENTO DE INSTALACIONES)
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT REFERENCES public.contact_messages(id) ON DELETE CASCADE,
    project_name TEXT NOT NULL,
    service_type TEXT NOT NULL,
    status TEXT DEFAULT 'Planificación'::text, -- 'Planificación', 'En Progreso', 'Completado', 'Cancelado'
    estimated_cost DECIMAL(12,2),
    actual_cost DECIMAL(12,2),
    start_date DATE,
    completion_date DATE,
    address TEXT,
    city TEXT,
    state TEXT,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABLA DE CITAS/REUNIONES
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT REFERENCES public.contact_messages(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    description TEXT,
    appointment_date TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_minutes INTEGER DEFAULT 60,
    status TEXT DEFAULT 'Programada'::text, -- 'Programada', 'Completada', 'Cancelada', 'Reprogramada'
    location TEXT,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABLA DE DOCUMENTOS (CONTRATOS, FACTURAS, ETC)
CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT REFERENCES public.contact_messages(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES public.projects(id) ON DELETE SET NULL,
    document_type TEXT NOT NULL, -- 'Contrato', 'Factura', 'Cotización', 'Manual', 'Certificado'
    title TEXT NOT NULL,
    file_url TEXT,
    file_name TEXT,
    file_size BIGINT,
    mime_type TEXT,
    description TEXT,
    is_public BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. TABLA DE KITS SOLARES (CATÁLOGO DE PRODUCTOS)
CREATE TABLE IF NOT EXISTS public.kits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL, -- 'Residencial', 'Comercial', 'Industrial'
    capacity INTEGER NOT NULL, -- Capacidad en watts
    price DECIMAL(10,2) NOT NULL, -- Precio en MXN
    stock INTEGER DEFAULT 0,
    description TEXT,
    panels INTEGER NOT NULL, -- Número de paneles
    inverter DECIMAL(6,2) NOT NULL, -- Capacidad del inversor en kW
    battery DECIMAL(6,2), -- Capacidad de batería en kWh (opcional)
    warranty INTEGER, -- Garantía en años (opcional)
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. TABLA DE SEGUIMIENTO DE COMUNICACIONES
CREATE TABLE IF NOT EXISTS public.communications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id BIGINT REFERENCES public.contact_messages(id) ON DELETE CASCADE,
    type TEXT NOT NULL, -- 'Email', 'Llamada', 'WhatsApp', 'Visita', 'Nota'
    subject TEXT,
    content TEXT NOT NULL,
    direction TEXT DEFAULT 'Saliente'::text, -- 'Entrante', 'Saliente'
    status TEXT DEFAULT 'Enviado'::text, -- 'Enviado', 'Recibido', 'Pendiente', 'Fallido'
    next_follow_up DATE,
    created_by TEXT, -- ID del usuario que creó la comunicación
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

